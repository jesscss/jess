#!/usr/bin/env node
/**
 * Read-only static complexity analysis of the GENERATED parseman grammar
 * artifacts (packages/syntax/<dialect>/<dialect>-parser/lib/grammar*.js).
 *
 * Writes nothing except stdout / an optional --json report path. Never touches
 * any src/grammar.ts.
 *
 * Metrics, per generated function, per grammar instance, per dialect:
 *  1. rollback-snapshot sites (6-field _ntl/_ntr/_ntt/_ntg/_ntf/_nte), split
 *     into attempt() vs not() shapes, and whether first-set pre-guarded
 *  2. choice arms + how many are first-set gated / share a non-discriminating
 *     guard
 *  3. duplicate (identical after identifier-number normalization) function
 *     bodies, and named rules that are never referenced (shadowed survivors)
 *  4. arm counts and nesting depth
 *  5. generated byte size
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

const ARTIFACTS = [
  ['css', 'packages/syntax/css/css-parser/lib/grammar.js'],
  ['less', 'packages/syntax/less/less-parser/lib/grammar2.js'],
  ['scss', 'packages/syntax/scss/scss-parser/lib/grammar.js'],
  ['jess', 'packages/syntax/jess/jess-parser/lib/grammar.js']
];

const INSTANCE_START = /^const (\w+) = \/\* @__PURE__ \*\/ Object\.defineProperty\(/;
const INSTANCE_END = /^\}\)\(\), Symbol\.for\("parseman\.leafComposed"\)/;
const FN_START = /^\tfunction (_r_[A-Za-z0-9_]+|_[0-9a-f]{8}__(?:pf|tf)\d+)\(/;
const FN_END = /^\t\}$/;

/** Strip numeric suffixes + build-hash prefixes so structurally identical code hashes alike. */
function normalize(body) {
  return body
    .replace(/_[0-9a-f]{8}__/g, '_H__')
    .replace(/\b(_[a-zA-Z]{1,8})\d+\b/g, '$1N');
}

function hash(s) {
  return createHash('sha1').update(s).digest('hex').slice(0, 12);
}

function analyzeFunction(name, lines, startLine) {
  const body = lines.join('\n');
  const norm = normalize(body);

  // --- 1. rollback snapshots -------------------------------------------------
  // parseman emits a 6-field snapshot for two constructs, distinguished by the
  // temp-var prefix it mints: `_atl/_atr/_att/_atg/_atf/_ate` = attempt(),
  // `_ntl/_ntr/_ntt/_ntg/_ntf/_nte` = not().  Both roll back _cstLeaves,
  // _cstRawChildren, _cstTriviaLog, _triviaLog, _fields and _errors.
  const snapshots = [];
  for (const [prefix, kind] of [['_atl', 'attempt'], ['_ntl', 'not']]) {
    const re = new RegExp(`const ${prefix}(\\d+) = _ctx\\._cstLeaves\\?\\.length`, 'g');
    for (const m of body.matchAll(re)) {
      const id = m[1];
      const declIdx = lines.findIndex(l => l.includes(`const ${prefix}${id} =`));
      const declLine = lines[declIdx] ?? '';
      // emitAttempt prepends a codePointAt first-set pre-guard (`_agcNN`) when
      // the inner parser has a computable first set.
      const guarded =
        /const _agc\d+ =/.test(lines[declIdx - 2] ?? '') ||
        /const _agc\d+ =/.test(lines[declIdx - 3] ?? '') ||
        /const _agc\d+ =/.test(lines[declIdx - 4] ?? '');
      snapshots.push({
        id: prefix + id,
        kind,
        firstSetGuarded: kind === 'attempt' ? guarded : null,
        line: startLine + declIdx,
        depth: (declLine.match(/^\t*/)?.[0].length ?? 0) - 1
      });
    }
  }

  // --- 2. choices ------------------------------------------------------------
  const choiceIds = [...body.matchAll(/\b_crok(\d+) = false/g)].map(m => m[1]);
  const choices = choiceIds.map(id => {
    const armRe = new RegExp(`^\\s*if \\(!_crok${id}\\)\\s*(?:if \\((.*?)\\)\\s*)?\\{\\s*$`);
    const arms = [];
    for (let i = 0; i < lines.length; i++) {
      const m = armRe.exec(lines[i]);
      if (!m) continue;
      // The choice's failure epilogue is an ungated `if (!_crokID) {` whose
      // block immediately assigns _ctx._fe — that is not an arm.
      if (!m[1] && /^\s*_ctx\._fe = /.test(lines[i + 1] ?? '')) continue;
      // How does an ungated arm discover it does not apply?  If the first
      // discriminating statement in the arm is an inline character test the arm
      // self-gates cheaply; if it is a call into another rule/fragment the arm
      // is entered blind and costs a call frame before it can be rejected.
      let entry = 'unknown';
      for (let j = i + 1; j < Math.min(i + 40, lines.length); j++) {
        const l = lines[j];
        if (/= (?:_r_[A-Za-z0-9_]+|_[0-9a-f]{8}__(?:pf|tf)\d+)\(input/.test(l)) { entry = 'call'; break; }
        if (/input\.charCodeAt\(|input\.codePointAt\(|\.lastIndex = |input\.startsWith\(/.test(l)) { entry = 'inline-test'; break; }
      }
      arms.push({ guard: (m[1] ?? '').trim(), entry });
    }
    const gated = arms.filter(a => a.guard.length > 0);
    const ungated = arms.filter(a => a.guard.length === 0);
    const byGuard = new Map();
    for (const g of gated) byGuard.set(g.guard, (byGuard.get(g.guard) ?? 0) + 1);
    const largestGuardGroup = byGuard.size ? Math.max(...byGuard.values()) : 0;
    return {
      id,
      arms: arms.length,
      gatedArms: gated.length,
      ungatedArms: ungated.length,
      ungatedCallFirst: ungated.filter(a => a.entry === 'call').length,
      ungatedInlineTest: ungated.filter(a => a.entry === 'inline-test').length,
      distinctGuards: byGuard.size,
      largestGuardGroup,
      guards: [...byGuard.entries()].sort((a, b) => b[1] - a[1]).slice(0, 4)
    };
  });

  // --- 4. nesting depth ------------------------------------------------------
  let maxDepth = 0;
  for (const l of lines) {
    const t = l.match(/^\t*/)[0].length;
    if (t > maxDepth) maxDepth = t;
  }

  // --- callees ---------------------------------------------------------------
  const callees = new Set(
    [...body.matchAll(/\b(_r_[A-Za-z0-9_]+|_[0-9a-f]{8}__(?:pf|tf)\d+)\(input, _pos|\b(_r_[A-Za-z0-9_]+|_[0-9a-f]{8}__(?:pf|tf)\d+)\(input, /g)]
      .map(m => m[1] ?? m[2])
      .filter(Boolean)
  );
  callees.delete(name);

  return {
    name,
    startLine,
    lines: lines.length,
    bytes: Buffer.byteLength(body, 'utf8'),
    normHash: hash(norm),
    snapshots,
    snapshotCount: snapshots.length,
    attemptSnapshots: snapshots.filter(s => s.kind === 'attempt').length,
    notSnapshots: snapshots.filter(s => s.kind === 'not').length,
    unguardedAttempts: snapshots.filter(s => s.kind === 'attempt' && !s.firstSetGuarded).length,
    choices,
    choiceCount: choices.length,
    totalArms: choices.reduce((a, c) => a + c.arms, 0),
    ungatedArms: choices.reduce((a, c) => a + c.ungatedArms, 0),
    ungatedCallFirst: choices.reduce((a, c) => a + c.ungatedCallFirst, 0),
    ungatedInlineTest: choices.reduce((a, c) => a + c.ungatedInlineTest, 0),
    gatedArms: choices.reduce((a, c) => a + c.gatedArms, 0),
    maxArms: choices.reduce((a, c) => Math.max(a, c.arms), 0),
    worstGuardGroup: choices.reduce((a, c) => Math.max(a, c.largestGuardGroup), 0),
    maxDepth,
    callees: [...callees]
  };
}

function analyzeArtifact(dialect, file) {
  const abs = path.join(ROOT, file);
  const src = readFileSync(abs, 'utf8');
  const lines = src.split('\n');

  const instances = [];
  let cur = null;
  let fn = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!cur) {
      const m = INSTANCE_START.exec(line);
      if (m) cur = { name: m[1], startLine: i + 1, endLine: null, fns: [] };
      continue;
    }
    if (INSTANCE_END.test(line)) {
      cur.endLine = i + 1;
      cur.bytes = Buffer.byteLength(lines.slice(cur.startLine - 1, i + 1).join('\n'), 'utf8');
      instances.push(cur);
      cur = null;
      continue;
    }
    if (fn) {
      fn.buf.push(line);
      if (FN_END.test(line)) {
        cur.fns.push(analyzeFunction(fn.name, fn.buf, fn.startLine));
        fn = null;
      }
      continue;
    }
    const fm = FN_START.exec(line);
    if (fm) fn = { name: fm[1], startLine: i + 1, buf: [line] };
  }

  for (const inst of instances) {
    const byName = new Map(inst.fns.map(f => [f.name, f]));
    const referenced = new Set();
    for (const f of inst.fns) for (const c of f.callees) referenced.add(c);
    inst.unreferenced = inst.fns.filter(f => !referenced.has(f.name)).map(f => f.name);

    // duplicate bodies (structurally identical after normalization)
    const byHash = new Map();
    for (const f of inst.fns) {
      if (!byHash.has(f.normHash)) byHash.set(f.normHash, []);
      byHash.get(f.normHash).push(f);
    }
    inst.duplicateGroups = [...byHash.values()]
      .filter(g => g.length > 1)
      .map(g => ({ hash: g[0].normHash, bytes: g[0].bytes, members: g.map(f => f.name) }))
      .sort((a, b) => b.bytes * b.members.length - a.bytes * a.members.length);

    // attribute fragments to the nearest named rules that reach them
    const callers = new Map();
    for (const f of inst.fns) {
      for (const c of f.callees) {
        if (!callers.has(c)) callers.set(c, new Set());
        callers.get(c).add(f.name);
      }
    }
    const owners = (frag, seen = new Set()) => {
      const out = new Set();
      const stack = [frag];
      while (stack.length) {
        const n = stack.pop();
        if (seen.has(n)) continue;
        seen.add(n);
        for (const c of callers.get(n) ?? []) {
          if (c.startsWith('_r_')) out.add(c);
          else stack.push(c);
        }
      }
      return [...out];
    };
    for (const f of inst.fns) {
      f.owners = f.name.startsWith('_r_') ? [f.name] : owners(f.name);
    }
    inst.byName = byName;
  }

  return { dialect, file, bytes: Buffer.byteLength(src, 'utf8'), lines: lines.length, instances };
}

const report = ARTIFACTS.map(([d, f]) => analyzeArtifact(d, f));

// ---------------------------------------------------------------------------
// stdout summary
// ---------------------------------------------------------------------------
const num = n => String(n).padStart(7);

console.log('=== ARTIFACTS ===');
for (const a of report) {
  console.log(`${a.dialect.padEnd(5)} ${a.file}  ${(a.bytes / 1e6).toFixed(2)} MB  ${a.lines} lines  instances=${a.instances.length}`);
  for (const inst of a.instances) {
    const fns = inst.fns;
    const rules = fns.filter(f => f.name.startsWith('_r_'));
    console.log(
      `   ${inst.name.padEnd(28)} ${(inst.bytes / 1e6).toFixed(2)}MB  fns=${num(fns.length)} rules=${num(rules.length)}` +
      ` snap=${num(fns.reduce((x, f) => x + f.snapshotCount, 0))}` +
      ` (attempt=${fns.reduce((x, f) => x + f.attemptSnapshots, 0)}, not=${fns.reduce((x, f) => x + f.notSnapshots, 0)})` +
      ` choices=${num(fns.reduce((x, f) => x + f.choiceCount, 0))}` +
      ` arms=${num(fns.reduce((x, f) => x + f.totalArms, 0))}` +
      ` ungated=${num(fns.reduce((x, f) => x + f.ungatedArms, 0))}` +
      ` (call-first=${fns.reduce((x, f) => x + f.ungatedCallFirst, 0)}, inline-test=${fns.reduce((x, f) => x + f.ungatedInlineTest, 0)})`
    );
  }
}

const primary = a => a.instances[0];

console.log('\n=== 1. ROLLBACK SNAPSHOT SITES (primary instance per dialect) ===');
for (const a of report) {
  const inst = primary(a);
  const sites = [];
  for (const f of inst.fns) {
    for (const s of f.snapshots) {
      sites.push({ fn: f.name, line: f.startLine, owners: f.owners, ...s });
    }
  }
  console.log(`\n--- ${a.dialect} (${inst.name}): ${sites.length} sites`);
  const byOwner = new Map();
  for (const s of sites) {
    const key = s.owners.length ? s.owners.join(',') : '(unattributed)';
    if (!byOwner.has(key)) byOwner.set(key, []);
    byOwner.get(key).push(s);
  }
  for (const [owner, ss] of [...byOwner.entries()].sort((x, y) => y[1].length - x[1].length)) {
    const at = ss.filter(s => s.kind === 'attempt').length;
    const nt = ss.filter(s => s.kind === 'not').length;
    const ug = ss.filter(s => s.kind === 'attempt' && !s.firstSetGuarded).length;
    console.log(`  ${String(ss.length).padStart(3)}  attempt=${at} (unguarded=${ug}) not=${nt}   ${owner.slice(0, 150)}`);
  }
}

console.log('\n=== 2. UN-GATED CHOICE ARMS — worst rules (primary instance) ===');
for (const a of report) {
  const inst = primary(a);
  const worst = inst.fns
    .filter(f => f.ungatedCallFirst > 0)
    .sort((x, y) => y.ungatedCallFirst - x.ungatedCallFirst)
    .slice(0, 15);
  console.log(`\n--- ${a.dialect}  (call-first = arm entered blind, costs a call frame before rejection)`);
  for (const f of worst) {
    console.log(
      `  ${String(f.ungatedCallFirst).padStart(3)} call-first + ${String(f.ungatedInlineTest).padStart(3)} inline-test ungated / ${String(f.totalArms).padStart(3)} arms  ` +
      `${f.name}:${f.startLine}  owners=${f.owners.slice(0, 3).join(',') || '-'}`
    );
  }
}

console.log('\n=== 2b. NON-DISCRIMINATING GATES (arms sharing one identical first-set guard) ===');
for (const a of report) {
  const inst = primary(a);
  const rows = [];
  for (const f of inst.fns) {
    for (const c of f.choices) {
      if (c.largestGuardGroup >= 3) {
        rows.push({ fn: f.name, line: f.startLine, owners: f.owners, ...c });
      }
    }
  }
  rows.sort((x, y) => y.largestGuardGroup - x.largestGuardGroup);
  console.log(`\n--- ${a.dialect}: ${rows.length} choices with >=3 arms behind one identical guard`);
  for (const r of rows.slice(0, 12)) {
    console.log(
      `  ${String(r.largestGuardGroup).padStart(3)} arms share guard "${r.guards[0][0].slice(0, 60)}"  ` +
      `(${r.arms} arms, ${r.distinctGuards} distinct guards)  ${r.fn}:${r.line} owners=${r.owners.slice(0, 2).join(',') || '-'}`
    );
  }
}

console.log('\n=== 3. DUPLICATED / SHADOWED PRODUCTIONS ===');
for (const a of report) {
  const inst = primary(a);
  console.log(`\n--- ${a.dialect} (${inst.name})`);
  console.log(`  duplicate-body groups: ${inst.duplicateGroups.length}, wasted bytes: ${inst.duplicateGroups.reduce((x, g) => x + g.bytes * (g.members.length - 1), 0)}`);
  for (const g of inst.duplicateGroups.slice(0, 8)) {
    console.log(`    x${g.members.length}  ${g.bytes}B each  ${g.members.slice(0, 6).join(', ')}`);
  }
  const deadRules = inst.unreferenced.filter(n => n.startsWith('_r_'));
  console.log(`  unreferenced named rules (${deadRules.length}): ${deadRules.slice(0, 30).join(', ')}`);
}

console.log('\n=== 3b. CROSS-DIALECT RULE DIVERGENCE ===');
{
  const names = new Map();
  for (const a of report) {
    const inst = primary(a);
    for (const f of inst.fns) {
      if (!f.name.startsWith('_r_')) continue;
      if (!names.has(f.name)) names.set(f.name, new Map());
      names.get(f.name).set(a.dialect, f);
    }
  }
  let identical = 0, diverged = 0;
  const divergedRows = [];
  for (const [n, m] of names) {
    if (m.size < 2) continue;
    const hashes = new Set([...m.values()].map(f => f.normHash));
    if (hashes.size === 1) identical++;
    else {
      diverged++;
      divergedRows.push({ name: n, dialects: [...m.keys()], bytes: [...m.values()].map(f => f.bytes) });
    }
  }
  console.log(`  rules present in >=2 dialects: ${identical + diverged}  identical=${identical}  diverged=${diverged}`);
  divergedRows.sort((x, y) => Math.max(...y.bytes) - Math.max(...x.bytes));
  for (const r of divergedRows.slice(0, 15)) {
    console.log(`    ${r.name.padEnd(38)} ${r.dialects.join('/')}  bytes=${r.bytes.join('/')}`);
  }
}

console.log('\n=== 4. ARM COUNT + NESTING DEPTH — worst rules ===');
for (const a of report) {
  const inst = primary(a);
  const worst = inst.fns.slice().sort((x, y) => y.maxArms - x.maxArms).slice(0, 10);
  console.log(`\n--- ${a.dialect}`);
  for (const f of worst) {
    console.log(`  maxArms=${String(f.maxArms).padStart(3)} choices=${String(f.choiceCount).padStart(3)} depth=${String(f.maxDepth).padStart(3)}  ${f.name}:${f.startLine} owners=${f.owners.slice(0, 2).join(',') || '-'}`);
  }
  const deep = inst.fns.slice().sort((x, y) => y.maxDepth - x.maxDepth).slice(0, 5);
  console.log('  deepest:');
  for (const f of deep) console.log(`    depth=${f.maxDepth} ${f.name}:${f.startLine} owners=${f.owners.slice(0, 2).join(',') || '-'}`);
}

console.log('\n=== 5. RULE SIZE (generated bytes), top 20 per dialect ===');
for (const a of report) {
  const inst = primary(a);
  console.log(`\n--- ${a.dialect}`);
  for (const f of inst.fns.slice().sort((x, y) => y.bytes - x.bytes).slice(0, 20)) {
    console.log(`  ${String(f.bytes).padStart(8)}B  arms=${String(f.totalArms).padStart(3)} snap=${String(f.snapshotCount).padStart(2)} depth=${String(f.maxDepth).padStart(2)}  ${f.name}:${f.startLine} owners=${f.owners.slice(0, 2).join(',') || '-'}`);
  }
}

const jsonArg = process.argv.indexOf('--json');
if (jsonArg !== -1 && process.argv[jsonArg + 1]) {
  const out = report.map(a => ({
    ...a,
    instances: a.instances.map(i => ({ ...i, byName: undefined }))
  }));
  writeFileSync(process.argv[jsonArg + 1], JSON.stringify(out, null, 1));
  console.log(`\nwrote ${process.argv[jsonArg + 1]}`);
}
