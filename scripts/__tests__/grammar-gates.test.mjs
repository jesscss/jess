/**
 * Canaries for the grammar artifact gate (`check-grammar-artifacts.mjs`) and the
 * grammar speed gate (`grammar-speed-gate.mjs`).
 *
 * A gate that passes on a healthy build proves nothing on its own, so each
 * failure class is shown failing here: a doctored artifact or a doctored
 * baseline must go red, and the committed baseline against the real build must
 * stay green. The artifact half reads the BUILT parser libs (CI runs this after
 * the clean build). The central canary is the 2026-08-31 regression itself:
 * the real CSS `ast.js` with its precompiled assembly stripped to `a: []`,
 * which is exactly what the Less, SCSS and `.jess` artifacts became
 * (jesscss/jess#508).
 */
import { strict as assert } from 'node:assert';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { BASELINE as ARTIFACT_BASELINE, GRAMMARS, compareArtifacts, measureGrammars, ratchetArtifacts } from '../check-grammar-artifacts.mjs';
import { COUNTERS, compareSpeed, envDiff, environment, selfTest } from '../grammar-speed-gate.mjs';
import { precompiledAssembly } from '../parseman-fallback-detector.mjs';

const root = resolve(fileURLToPath(import.meta.url), '../../..');
const require = createRequire(import.meta.url);
const espree = require(require.resolve('espree', { paths: [require.resolve('eslint')] }));

const clone = value => structuredClone(value);
const artifactBaseline = JSON.parse(readFileSync(join(root, ARTIFACT_BASELINE), 'utf8'));
const measured = measureGrammars(root);
const AST_JS = 'lib/grammar/ast.js';
const cssAstCode = readFileSync(join(root, GRAMMARS.css, AST_JS), 'utf8');

/** The artifact with its table's `a: [...]` inventory replaced by `a: []`: same table, nothing precompiled. */
function stripAssembly(code) {
  const ast = espree.parse(code, { ecmaVersion: 'latest', sourceType: 'module', range: true });
  let range;
  const visit = (node) => {
    if (range || node === null || typeof node !== 'object') {
      return;
    }
    if (node.type === 'Property' && node.key?.name === 'a' && node.value.type === 'ArrayExpression') {
      range = node.value.range;
      return;
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) {
        value.forEach(visit);
      } else if (value && typeof value.type === 'string') {
        visit(value);
      }
    }
  };
  visit(ast);
  assert.ok(range, 'no `a:` inventory found in the artifact');
  return code.slice(0, range[0]) + '[]' + code.slice(range[1]);
}

function withArtifact(grammar, path, code) {
  const doctored = clone(measured);
  doctored[grammar].artifacts[path] = {
    bytes: Buffer.byteLength(code),
    assemblyFunctions: precompiledAssembly(code)?.functions ?? null
  };
  return doctored;
}

test('artifact gate passes the committed baseline on this build', () => {
  assert.deepEqual(compareArtifacts(measured, artifactBaseline), { failures: [], unbanked: [] });
});

test('the real CSS ast.js carries a precompiled assembly; the interpreter build carries no table', () => {
  assert.ok(precompiledAssembly(cssAstCode).functions > 0);
  const interpreter = readFileSync(join(root, GRAMMARS.css, 'lib/grammar/interpreter/ast.js'), 'utf8');
  assert.equal(precompiledAssembly(interpreter), null);
});

test('2026-08-31 canary: CSS ast.js stripped to `a: []` fails as ASSEMBLY LOST, and is smaller', () => {
  const stripped = stripAssembly(cssAstCode);
  assert.deepEqual(precompiledAssembly(stripped), { assemblies: 0, functions: 0 });
  assert.ok(stripped.length < cssAstCode.length, 'losing the assembly shrinks the artifact — the false win');
  const { failures } = compareArtifacts(withArtifact('css', AST_JS, stripped), artifactBaseline);
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: ASSEMBLY LOST`)), failures.join('\n'));
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: TABLES ONLY`)), failures.join('\n'));
});

test('one extra generated byte fails as SIZE GREW', () => {
  const { failures } = compareArtifacts(withArtifact('css', AST_JS, `${cssAstCode} `), artifactBaseline);
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: SIZE GREW`)), failures.join('\n'));
});

test('removing grammar-source comments moves the ratio but not the bytes, and does not fail', () => {
  const doctored = clone(measured);
  doctored.css.sourceBytes -= 5000;
  assert.deepEqual(compareArtifacts(doctored, artifactBaseline).failures, []);
});

test('grammar source added with the generated bytes buys none: the artifact still fails as SIZE GREW', () => {
  const doctored = clone(measured);
  doctored.css.sourceBytes += 20_000;
  doctored.css.artifacts[AST_JS].bytes += 1_000;
  const { failures } = compareArtifacts(doctored, artifactBaseline);
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: SIZE GREW`)), failures.join('\n'));
});

test('bytes that shrink while the grammar source shrinks more are still unbanked', () => {
  const doctored = clone(measured);
  doctored.css.sourceBytes -= 20_000;
  doctored.css.artifacts[AST_JS].bytes -= 1_000;
  const { failures, unbanked } = compareArtifacts(doctored, artifactBaseline);
  assert.deepEqual(failures, []);
  assert.ok(unbanked.some(u => u.startsWith(`css ${AST_JS}: size shrank`)), unbanked.join('\n'));
});

test('an over-budget artifact with no named debt fails as OVER BUDGET', () => {
  const over = clone(measured);
  over.css.artifacts[AST_JS].bytes = over.css.sourceBytes * 6;
  const { failures } = compareArtifacts(over, artifactBaseline);
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: OVER BUDGET`)), failures.join('\n'));
});

test('over-budget debt does not carry over to another parseman version: a bump must bring every artifact within 5x', () => {
  const bumpedParseman = `${artifactBaseline.debtParseman}-next`;
  const over = clone(measured);
  over.css.artifacts[AST_JS].bytes = over.css.sourceBytes * 6;
  const indebted = clone(artifactBaseline);
  Object.assign(indebted.grammars.css.artifacts[AST_JS], { bytes: over.css.artifacts[AST_JS].bytes, ratio: 6, overBudget: 'named debt' });
  assert.deepEqual(compareArtifacts(over, indebted).failures, []);
  const { failures } = compareArtifacts(over, indebted, bumpedParseman);
  assert.ok(failures.some(f => f.startsWith(`css ${AST_JS}: OVER BUDGET`) && f.includes('does not carry over')), failures.join('\n'));
  const within = clone(measured);
  within.css.artifacts[AST_JS].bytes = within.css.sourceBytes * 5;
  const bumped = compareArtifacts(within, indebted, bumpedParseman);
  assert.deepEqual(bumped.failures, []);
  const ratcheted = ratchetArtifacts(within, indebted, bumpedParseman);
  assert.equal(ratcheted.debtParseman, bumpedParseman);
  assert.equal(ratcheted.grammars.css.artifacts[AST_JS].overBudget, undefined);
  assert.deepEqual(compareArtifacts(within, ratcheted, bumpedParseman), { failures: [], unbanked: [] });
});

test('a tables-only grammar with no named debt fails as TABLES ONLY', () => {
  const baseline = clone(artifactBaseline);
  delete baseline.grammars.jess.tablesOnly;
  const { failures } = compareArtifacts(measured, baseline);
  assert.ok(failures.some(f => f.startsWith(`jess ${AST_JS}: TABLES ONLY`)), failures.join('\n'));
});

test('regaining assembly is unbanked until pinned; the ratchet pins it and drops the debt', () => {
  const doctored = clone(measured);
  doctored.jess.artifacts[AST_JS].assemblyFunctions = 1217;
  const { failures, unbanked } = compareArtifacts(doctored, artifactBaseline);
  assert.deepEqual(failures, []);
  assert.ok(unbanked.some(u => u.startsWith(`jess ${AST_JS}: assembly grew`)), unbanked.join('\n'));
  assert.ok(unbanked.some(u => u.startsWith('jess: lib/grammar/ast.js carries 1217')), unbanked.join('\n'));
  const ratcheted = ratchetArtifacts(doctored, artifactBaseline);
  assert.equal(ratcheted.grammars.jess.tablesOnly, undefined);
  assert.deepEqual(compareArtifacts(doctored, ratcheted), { failures: [], unbanked: [] });
  const lost = clone(doctored);
  lost.jess.artifacts[AST_JS].assemblyFunctions = 0;
  assert.ok(compareArtifacts(lost, ratcheted).failures.some(f => f.startsWith(`jess ${AST_JS}: ASSEMBLY LOST`)));
});

test('a new or missing artifact fails', () => {
  const extra = clone(measured);
  extra.css.artifacts['lib/grammar/extra.js'] = { bytes: 1, assemblyFunctions: 0 };
  assert.ok(compareArtifacts(extra, artifactBaseline).failures.some(f => f.includes('extra.js: NEW')));
  const missing = clone(measured);
  delete missing.css.artifacts[AST_JS];
  assert.ok(compareArtifacts(missing, artifactBaseline).failures.some(f => f.startsWith(`css ${AST_JS}: GONE`)));
});

const speedBaseline = {
  tolerancePct: 1,
  grammars: { css: { instructionsPerParse: 100_000_000 }, less: { instructionsPerParse: 400_000_000 } }
};
const speed = (css, less, spreadPct = 0.1) => ({ css: { marginal: css, spreadPct }, less: { marginal: less, spreadPct } });

test('speed gate passes within tolerance', () => {
  assert.deepEqual(compareSpeed(speed(100_900_000, 396_500_000), speedBaseline), { failures: [], unbanked: [] });
});

test('2026-08-31 canary: Less at 27.6/16.9 of its baseline fails as REGRESSED', () => {
  const { failures } = compareSpeed(speed(100_000_000, Math.round(400_000_000 * 27.6 / 16.9)), speedBaseline);
  assert.equal(failures.length, 1);
  assert.match(failures[0], /^less: REGRESSED/);
});

test('a regression just past the tolerance fails; a win past it is unbanked', () => {
  assert.match(compareSpeed(speed(101_100_000, 400_000_000), speedBaseline).failures[0], /^css: REGRESSED/);
  const { failures, unbanked } = compareSpeed(speed(98_800_000, 400_000_000), speedBaseline);
  assert.deepEqual(failures, []);
  assert.match(unbanked[0], /^css: faster/);
});

test('a measurement noisier than the tolerance fails as UNSTABLE', () => {
  assert.match(compareSpeed(speed(100_000_000, 400_000_000, 1.5), speedBaseline).failures[0], /UNSTABLE/);
});

test('a grammar missing from the measurement or the baseline fails', () => {
  assert.match(compareSpeed({ css: { marginal: 100_000_000, spreadPct: 0 } }, speedBaseline).failures[0], /^less: baselined but not measured/);
  const extra = { ...speed(100_000_000, 400_000_000), scss: { marginal: 1, spreadPct: 0 } };
  assert.match(compareSpeed(extra, speedBaseline).failures[0], /^scss: NEW/);
});

test('the in-run self-test catches a doctored baseline, and reports blindness', () => {
  assert.equal(selfTest(speed(100_000_000, 400_000_000), speedBaseline), true);
  assert.equal(selfTest(speed(100_000_000, 400_000_000), { ...speedBaseline, tolerancePct: Number.NaN }), false);
});

test('both counters read their tool output', () => {
  assert.equal(COUNTERS.linux.read('==123== \n==123== I refs:        12,345,678,901\n'), '12345678901');
  assert.equal(COUNTERS.darwin.read('        10315021308  instructions retired\n'), '10315021308');
  assert.equal(COUNTERS.linux.read('valgrind: failed to start'), undefined);
});

test('an environment change is caught field by field: runner image, Valgrind, Node', () => {
  const recorded = JSON.parse(readFileSync(join(root, 'scripts/grammar-speed.baseline.json'), 'utf8')).env;
  assert.deepEqual(envDiff(structuredClone(recorded), recorded), []);
  for (const [field, value] of [['runnerImage', 'ubuntu28'], ['os', 'ubuntu-28.04'], ['valgrind', 'valgrind-3.27.0'], ['node', 'v24.23.0']]) {
    const moved = { ...recorded, [field]: value };
    const diff = envDiff(moved, recorded);
    assert.equal(diff.length, 1, diff.join('\n'));
    assert.match(diff[0], new RegExp(`^${field}: `));
  }
  assert.ok(envDiff({ ...recorded, valgrind: undefined }, recorded).some(d => d.startsWith('valgrind: ')), 'a missing field is a change');
  assert.ok(['counter', 'platform', 'os', 'runnerImage', 'valgrind', 'node', 'method'].every(k => k in environment()));
});
