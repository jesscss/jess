/**
 * Generates the naming-cost probe grammars (Candidate B tournament scaffolding).
 *
 * Four grammars with identical accepted languages, differing only in whether
 * the 20 sub-productions are NAMED (returned from the rules map, so codegen
 * never inlines them) or ANONYMOUS (inlined at each use site), crossed with
 * how many times each is used. The deltas give the per-name artifact cost and
 * the use-count crossover where naming starts paying for itself.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, '..', 'src');
const COUNT = 20;

/** A body with enough shape that inlining it is a real duplication. */
function body(index) {
  return `sequence(
      literal('r${index}('),
      optional(g.Identifier),
      many(choice(g.NumberToken, g.HexColor, g.DoubleQuotedText)),
      optional(sequence(literal(','), g.DimensionUnit)),
      literal(')')
    )`;
}

function generate({ named, uses }) {
  const decls = Array.from({ length: COUNT }, (_, i) => `  const R${i} = node(
    'R${i}',
    ${body(i)},
    () => null
  );`).join('\n\n');

  const arms = [];
  for (let use = 0; use < uses; use++) {
    for (let i = 0; i < COUNT; i++) {
      arms.push(named ? `g.R${i}` : `R${i}`);
    }
  }

  const returned = named
    ? ['Stylesheet', ...Array.from({ length: COUNT }, (_, i) => `R${i}`)]
    : ['Stylesheet'];

  const selfNames = ['Stylesheet', ...Array.from({ length: COUNT }, (_, i) => `R${i}`)]
    .map(n => `'${n}'`)
    .join(' | ');

  return `/**
 * Naming-cost probe: ${named ? 'NAMED' : 'ANONYMOUS'} sub-productions, ${uses} use(s) each.
 *
 * Generated by scripts/gen-name-probes.mjs. Do not edit by hand.
 */
import { choice, classifiedTrivia, composeLeaf, literal, many, node, optional, regex, rules, sequence } from 'parseman' with { type: 'macro' };
import type { Combinator } from 'parseman';
import { cssSyntax } from '@jesscss/parser-shared/recognition';
import { opaqueAtRuleRecognition } from '@jesscss/parser-shared/opaque-at-rule';
import { cssPseudoSyntax } from '@jesscss/parser-shared/pseudo-consts';

const blockComment = regex(/\\/\\*(?:[^*]|\\*(?!\\/))*\\*\\//);
const whitespaceRun = regex(/[ \\t\\n\\r\\f]+/);
const whitespace = classifiedTrivia({ whitespace: whitespaceRun, blockComment });

type Leaf = 'Identifier' | 'NumberToken' | 'HexColor' | 'DoubleQuotedText' | 'DimensionUnit';

type ProbeSelf = { readonly [K in Leaf | ${selfNames}]: Combinator<unknown> };

const probeFactory = (g: ProbeSelf) => {
${decls}

  const Stylesheet = node(
    'Stylesheet',
    many(choice(
      ${arms.join(',\n      ')}
    )),
    () => null
  );

  return { ${returned.join(', ')} };
};

export const probe = composeLeaf([cssSyntax, opaqueAtRuleRecognition, cssPseudoSyntax, rules(
  { trivia: whitespace },
  probeFactory
)]);
`;
}

const cases = [
  { name: 'probe-name-named-1', named: true, uses: 1 },
  { name: 'probe-name-inline-1', named: false, uses: 1 },
  { name: 'probe-name-named-3', named: true, uses: 3 },
  { name: 'probe-name-inline-3', named: false, uses: 3 }
];

mkdirSync(srcDir, { recursive: true });
for (const testCase of cases) {
  writeFileSync(join(srcDir, `${testCase.name}.ts`), generate(testCase));
}

const config = `import { defineConfig } from 'tsdown';
import parseman from 'parseman/plugin';

/** Generated by scripts/gen-name-probes.mjs. Do not edit by hand. */
export default defineConfig([
${cases.map(testCase => `  {
    entry: { '${testCase.name}': './src/${testCase.name}.ts' },
    format: ['esm'],
    dts: false,
    outDir: './probe',
    platform: 'node',
    fixedExtension: false,
    hash: false,
    clean: false,
    deps: { onlyBundle: false },
    plugins: [parseman.rolldown()]
  }`).join(',\n')}
]);
`;
writeFileSync(join(here, '..', 'tsdown.name-probes.mts'), config);
console.log(`wrote ${cases.length} probes`);
